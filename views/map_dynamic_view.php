<script>
(() => {
  const stage = document.getElementById('warehouseStage');
  const pxPerMeter = 40;
  const apiUrl = 'map_layout_api.php';
  const defaultShelves = <?php echo json_encode($defaultShelves, JSON_UNESCAPED_UNICODE); ?>;

  const fixedZones = [
    { label: 'Oficina', x: 30, y: 20, w: 160, h: 90 },
    { label: 'Baños', x: 210, y: 20, w: 90, h: 90 },
    { label: 'Elevador/Montacargas', x: 820, y: 20, w: 150, h: 120 },
    { label: 'Pared / Límite', x: 0, y: 0, w: 1000, h: 950, borderOnly: true }
  ];

  let shelves = [];
  let selectedId = null;
  let addMode = false;

  function showMessage(type, text) {
    const wrapper = document.createElement('div');
    wrapper.className = `alert alert-${type} py-2 px-3 mt-2`;
    wrapper.textContent = text;
    stage.parentElement.appendChild(wrapper);
    setTimeout(() => wrapper.remove(), 2600);
  }

  function normalizeShelf(raw) {
    return {
      id: String(raw.id || '').trim(),
      x: Number(raw.x) || 40,
      y: Number(raw.y) || 40,
      width: Math.max(0.1, Number(raw.width) || 1.8),
      length: Math.max(0.1, Number(raw.length) || 1.8),
      depth: Math.max(0.1, Number(raw.depth) || 1),
      levels: Math.max(1, parseInt(raw.levels || 1, 10)),
      capacity: Math.max(1, parseInt(raw.capacity || 100, 10)),
      unit: raw.unit === 'lbs' ? 'lbs' : 'kg',
      color: raw.color || '#1976d2',
      rotation: [0, 90, 180, 270].includes(Number(raw.rotation)) ? Number(raw.rotation) : 0
    };
  }

  function getShelfRect(shelf) {
    const baseW = shelf.width * pxPerMeter;
    const baseH = shelf.length * pxPerMeter;
    if (shelf.rotation === 90 || shelf.rotation === 270) {
      return { width: baseH, height: baseW };
    }
    return { width: baseW, height: baseH };
  }

  function updateActionLinks(shelf) {
    document.getElementById('cfgAddItem').href = 'add_product.php?shelf_filter=' + encodeURIComponent(shelf.id);
    document.getElementById('cfgMoveItem').href = 'add_movement.php?shelf_filter=' + encodeURIComponent(shelf.id);
    document.getElementById('cfgViewItems').href = 'product.php?shelf_filter=' + encodeURIComponent(shelf.id);
  }

  function render() {
    stage.innerHTML = '';

    fixedZones.forEach((zone) => {
      const z = document.createElement('div');
      z.className = 'fixed-zone';
      z.style.left = zone.x + 'px';
      z.style.top = zone.y + 'px';
      z.style.width = zone.w + 'px';
      z.style.height = zone.h + 'px';
      if (zone.borderOnly) {
        z.style.background = 'transparent';
        z.style.border = '3px solid rgba(255,255,255,.2)';
      } else {
        z.textContent = zone.label;
      }
      stage.appendChild(z);
    });

    shelves.forEach((shelf) => {
      const el = document.createElement('div');
      const rect = getShelfRect(shelf);
      el.className = 'shelf-item' + (selectedId === shelf.id ? ' selected' : '');
      el.style.left = shelf.x + 'px';
      el.style.top = shelf.y + 'px';
      el.style.width = rect.width + 'px';
      el.style.height = rect.height + 'px';
      el.style.background = shelf.color;
      el.dataset.id = shelf.id;
      el.title = `${shelf.id} | ${shelf.width}x${shelf.length}x${shelf.depth} ${shelf.unit} | Niveles: ${shelf.levels} | Cap: ${shelf.capacity} ${shelf.unit}`;

      const label = document.createElement('span');
      label.className = 'label';
      label.textContent = shelf.id;
      el.appendChild(label);

      makeDraggable(el);
      el.addEventListener('click', (ev) => {
        ev.stopPropagation();
        openConfig(shelf.id);
      });
      stage.appendChild(el);
    });

    stage.classList.toggle('place-mode', addMode);
  }

  function makeDraggable(el) {
    let isDown = false;
    let offsetX = 0;
    let offsetY = 0;

    el.addEventListener('mousedown', (ev) => {
      isDown = true;
      const rect = el.getBoundingClientRect();
      offsetX = ev.clientX - rect.left;
      offsetY = ev.clientY - rect.top;
      selectedId = el.dataset.id;
      render();
      ev.preventDefault();
    });

    window.addEventListener('mousemove', (ev) => {
      if (!isDown) return;
      const shelf = shelves.find(s => s.id === el.dataset.id);
      if (!shelf) return;
      const stageRect = stage.getBoundingClientRect();
      const rect = getShelfRect(shelf);

      let x = ev.clientX - stageRect.left - offsetX;
      let y = ev.clientY - stageRect.top - offsetY;
      x = Math.max(0, Math.min(stage.clientWidth - rect.width, x));
      y = Math.max(0, Math.min(stage.clientHeight - rect.height, y));

      shelf.x = Math.round(x);
      shelf.y = Math.round(y);
      el.style.left = shelf.x + 'px';
      el.style.top = shelf.y + 'px';
    });

    window.addEventListener('mouseup', () => { isDown = false; });
  }

  function openConfig(id) {
    const shelf = shelves.find(s => s.id === id);
    if (!shelf) return;
    selectedId = shelf.id;
    document.getElementById('cfgShelfName').textContent = shelf.id;
    document.getElementById('cfgId').value = shelf.id;
    document.getElementById('cfgColor').value = shelf.color;
    document.getElementById('cfgWidth').value = shelf.width;
    document.getElementById('cfgLength').value = shelf.length;
    document.getElementById('cfgDepth').value = shelf.depth;
    document.getElementById('cfgLevels').value = shelf.levels;
    document.getElementById('cfgCapacity').value = shelf.capacity;
    document.getElementById('cfgUnit').value = shelf.unit;
    document.getElementById('cfgRotation').value = shelf.rotation;
    updateActionLinks(shelf);
    render();

    const modal = new bootstrap.Modal(document.getElementById('shelfConfigModal'));
    modal.show();
  }

  function applyConfig() {
    const shelf = shelves.find(s => s.id === selectedId);
    if (!shelf) return;

    const nextId = String(document.getElementById('cfgId').value || '').trim();
    if (!nextId) return showMessage('danger', 'El ID es obligatorio.');
    if (nextId !== shelf.id && shelves.some(s => s.id === nextId)) {
      return showMessage('danger', 'Ese ID ya existe.');
    }

    shelf.id = nextId;
    shelf.color = document.getElementById('cfgColor').value;
    shelf.width = Math.max(0.1, Number(document.getElementById('cfgWidth').value));
    shelf.length = Math.max(0.1, Number(document.getElementById('cfgLength').value));
    shelf.depth = Math.max(0.1, Number(document.getElementById('cfgDepth').value));
    shelf.levels = Math.max(1, parseInt(document.getElementById('cfgLevels').value, 10) || 1);
    shelf.capacity = Math.max(1, parseInt(document.getElementById('cfgCapacity').value, 10) || 1);
    shelf.unit = document.getElementById('cfgUnit').value === 'lbs' ? 'lbs' : 'kg';
    shelf.rotation = Number(document.getElementById('cfgRotation').value);
    selectedId = shelf.id;

    const rect = getShelfRect(shelf);
    shelf.x = Math.min(shelf.x, stage.clientWidth - rect.width);
    shelf.y = Math.min(shelf.y, stage.clientHeight - rect.height);

    updateActionLinks(shelf);
    render();
    showMessage('success', 'Anaquel actualizado.');
  }

  async function loadLayout() {
    try {
      const res = await fetch(apiUrl + '?action=load', { credentials: 'same-origin' });
      const json = await res.json();
      if (json && json.success && Array.isArray(json.layout?.shelves) && json.layout.shelves.length) {
        shelves = json.layout.shelves.map(normalizeShelf);
      } else {
        shelves = defaultShelves.map(normalizeShelf);
      }
    } catch (e) {
      shelves = defaultShelves.map(normalizeShelf);
    }
    render();
  }

  async function saveLayout() {
    const payload = {
      shelves,
      pxPerMeter,
      updatedAt: new Date().toISOString()
    };

    const res = await fetch(apiUrl + '?action=save', {
      method: 'POST',
      credentials: 'same-origin',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    const json = await res.json();
    if (json.success) {
      showMessage('success', 'Layout guardado correctamente.');
    } else {
      showMessage('danger', json.message || 'No se pudo guardar.');
    }
  }

  function exportLayout() {
    const payload = {
      shelves,
      pxPerMeter,
      exportedAt: new Date().toISOString()
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'warehouse_layout.json';
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  }

  document.getElementById('btnAddShelf').addEventListener('click', () => {
    addMode = !addMode;
    render();
    showMessage('info', addMode ? 'Haz clic en el mapa para posicionar el nuevo anaquel.' : 'Modo agregar cancelado.');
  });

  stage.addEventListener('click', (ev) => {
    if (!addMode) return;
    if (ev.target.closest('.shelf-item')) return;

    const name = prompt('ID del nuevo anaquel (ej. AA1):');
    if (!name) return;
    if (shelves.some(s => s.id.toLowerCase() === name.trim().toLowerCase())) {
      return showMessage('danger', 'Ya existe un anaquel con ese ID.');
    }

    const rect = stage.getBoundingClientRect();
    const newShelf = normalizeShelf({
      id: name.trim(),
      x: Math.round(ev.clientX - rect.left),
      y: Math.round(ev.clientY - rect.top),
      width: 2,
      length: 2,
      depth: 1,
      levels: 3,
      capacity: 500,
      unit: 'kg',
      color: '#3949ab',
      rotation: 0
    });

    shelves.push(newShelf);
    selectedId = newShelf.id;
    addMode = false;
    render();
    openConfig(newShelf.id);
  });

  document.getElementById('btnApplyShelf').addEventListener('click', applyConfig);
  document.getElementById('btnSaveLayout').addEventListener('click', saveLayout);
  document.getElementById('btnExportLayout').addEventListener('click', exportLayout);

  document.getElementById('btnDeleteShelf').addEventListener('click', () => {
    if (!selectedId) return;
    if (!confirm('¿Eliminar este anaquel?')) return;
    shelves = shelves.filter(s => s.id !== selectedId);
    selectedId = null;
    render();
    bootstrap.Modal.getInstance(document.getElementById('shelfConfigModal'))?.hide();
  });

  loadLayout();
})();
</script>
